// Generates assets/js/mapdata.js — a dot-matrix of Africa + the Arabian Peninsula.
// Source: Natural Earth (public domain) via the `world-atlas` npm package. No borders are drawn.
// Run from /tools:  node build-map.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { feature } from 'topojson-client';
import { geoAzimuthalEqualArea, geoContains, geoBounds } from 'd3-geo';
const require = createRequire(import.meta.url);
const topo = JSON.parse(readFileSync(require.resolve('world-atlas/countries-50m.json'), 'utf8'));
const countries = feature(topo, topo.objects.countries).features;

const AFRICA = new Set(["Algeria","Angola","Benin","Botswana","Burkina Faso","Burundi","Cabo Verde","Cameroon","Central African Rep.","Chad","Comoros","Congo","Dem. Rep. Congo","Djibouti","Egypt","Eq. Guinea","Eritrea","eSwatini","Ethiopia","Gabon","Gambia","Ghana","Guinea","Guinea-Bissau","Côte d'Ivoire","Kenya","Lesotho","Liberia","Libya","Madagascar","Malawi","Mali","Mauritania","Mauritius","Morocco","Mozambique","Namibia","Niger","Nigeria","Rwanda","São Tomé and Principe","Senegal","Seychelles","Sierra Leone","Somalia","Somaliland","South Africa","S. Sudan","Sudan","Tanzania","Togo","Tunisia","Uganda","W. Sahara","Zambia","Zimbabwe"]);
const GULF = new Set(["United Arab Emirates","Saudi Arabia","Oman","Qatar","Bahrain","Kuwait"]);
const names = new Set(countries.map(c => c.properties.name));
for (const n of [...AFRICA, ...GULF]) if (!names.has(n)) console.warn('name not in atlas:', n);

const W = 1000, H = 1080;
const proj = geoAzimuthalEqualArea().rotate([-24, -2]).scale(640).translate([W * 0.44, H * 0.5]);
const boxed = countries.map(c => ({ c, b: geoBounds(c) }));
const find = (lon, lat) => {
  for (const { c, b } of boxed) {
    const [[x0, y0], [x1, y1]] = b;
    const inLon = x0 <= x1 ? (lon >= x0 && lon <= x1) : (lon >= x0 || lon <= x1);
    if (!inLon || lat < y0 || lat > y1) continue;
    if (geoContains(c, [lon, lat])) return c.properties.name;
  }
  return null;
};
const step = 15.5, rowH = step * Math.sqrt(3) / 2;
const dots = [];
let row = 0;
for (let y = step; y < H - step / 2; y += rowH, row++) {
  for (let x = step + (row % 2 ? step / 2 : 0); x < W - step / 2; x += step) {
    const ll = proj.invert([x, y]); if (!ll) continue;
    const name = find(ll[0], ll[1]); if (!name) continue;
    const f = AFRICA.has(name) ? 1 : GULF.has(name) ? 2 : 0;
    dots.push([Math.round(x * 10) / 10, Math.round(y * 10) / 10, f]);
  }
}
const pt = (lon, lat) => proj([lon, lat]).map(v => Math.round(v * 10) / 10);
const out = {
  w: W, h: H,
  nairobi: pt(36.82, -1.29),
  dubai: pt(55.27, 25.2),
  dots
};
const counts = dots.reduce((a, d) => (a[d[2]]++, a), [0, 0, 0]);
console.log('dots', dots.length, 'other/africa/gulf', counts, 'nairobi', out.nairobi, 'dubai', out.dubai);
writeFileSync(new URL('../assets/js/mapdata.js', import.meta.url),
  '/* Dot-matrix map data (Natural Earth, public domain). Generated by tools/build-map.mjs */\n' +
  'window.SR_MAP=' + JSON.stringify(out) + ';\n');
